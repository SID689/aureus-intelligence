#!/usr/bin/env bash
#
# One command between a laptop and a room full of phones.
#
#   ./scripts/demo_up.sh
#
# Brings the stack up, seeds the showcase, opens a public HTTPS address
# with a Cloudflare quick tunnel, rewrites the two environment values that
# have to match that address, restarts the frontend so it picks them up,
# and prints the URL to put on a slide.
#
# Why a tunnel and not a cloud deployment: nothing cold-starts, nothing
# sleeps, the database is the one already full of scanner history, and the
# address is live in about ninety seconds. The free cloud path is in
# docs/DEMO_DEPLOYMENT.md for when the demo has to outlive the laptop.
#
# The address changes every run. That is the one real cost of a quick
# tunnel, and it is why the QR code is generated by the app itself at
# /demo/qr rather than printed here: whatever the address is today, the
# slide is correct.
#
# Ctrl-C stops the tunnel and puts the environment back.

set -euo pipefail

cd "$(dirname "$0")/.."
ENV_FILE="frontend/.env.local"
BACKUP="frontend/.env.local.predemo"

step() { printf "\n\033[1;33m%s\033[0m %s\n" "──" "$1"; }
fail() { printf "\n\033[1;31m%s\033[0m %s\n" "✗" "$1"; exit 1; }

command -v docker >/dev/null || fail "Docker is not installed."
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is not available."
command -v cloudflared >/dev/null || fail "cloudflared is not installed. Run: brew install cloudflared"

# ── Environment values the demo needs ────────────────────────────────
# DEMO_MODE gates the presentation environment on the backend;
# NEXT_PUBLIC_DEMO_MODE compiles the entry point into the frontend. This
# script sets both, so it pairs with demo_down.sh with no manual edit in
# between.
step "Switching the flags on"
python3 - <<'FLAGS'
import pathlib, re
for path, key in (("backend/.env", "DEMO_MODE"),
                  ("frontend/.env.local", "NEXT_PUBLIC_DEMO_MODE")):
    p = pathlib.Path(path)
    if not p.exists():
        raise SystemExit(f"{path} does not exist. Copy it from the example first.")
    text = p.read_text(encoding="utf-8")
    if re.search(rf"(?m)^{key}=", text):
        text = re.sub(rf"(?m)^{key}=.*$", f"{key}=true", text)
    else:
        text = text.rstrip("\n") + f"\n{key}=true\n"
    p.write_text(text, encoding="utf-8")
    print(f"  {path}: {key}=true")
FLAGS

step "Starting the stack"
docker compose up -d
# --force-recreate on the backend, whose environment comes from
# `env_file:` and is fixed when the container is created: a restart keeps
# whatever DEMO_MODE the container was born with.
docker compose up -d --force-recreate backend > /dev/null
docker compose exec -T db pg_isready -U aureus >/dev/null 2>&1 || sleep 5

step "Seeding the showcase"
docker compose exec -T backend python -m scripts.seed_demo

step "Opening a public address"
cp "$ENV_FILE" "$BACKUP"
TUNNEL_LOG=$(mktemp)
cloudflared tunnel --url http://localhost:3000 --no-autoupdate > "$TUNNEL_LOG" 2>&1 &
TUNNEL_PID=$!

restore() {
  printf "\n"
  step "Stopping the tunnel and restoring the environment"
  kill "$TUNNEL_PID" 2>/dev/null || true
  [ -f "$BACKUP" ] && mv "$BACKUP" "$ENV_FILE"
  docker compose up -d --force-recreate frontend >/dev/null 2>&1 || true
  printf "Done. The stack is still running: docker compose ps\n"
}
trap restore EXIT INT TERM

PUBLIC_URL=""
for _ in $(seq 1 40); do
  PUBLIC_URL=$(grep -o 'https://[a-z0-9-]*\.trycloudflare\.com' "$TUNNEL_LOG" | head -1 || true)
  [ -n "$PUBLIC_URL" ] && break
  sleep 1
done
[ -n "$PUBLIC_URL" ] || fail "The tunnel did not report an address. Log: $TUNNEL_LOG"

step "Pointing the app at $PUBLIC_URL"
# NEXTAUTH_URL has to be the address the BROWSER used or every sign-in
# redirect lands back on localhost, which a phone cannot reach. The
# WebSocket base is deleted rather than set: unset means same origin, and
# the /api/v1 rewrite carries the upgrade through the one tunnel.
python3 - "$ENV_FILE" "$PUBLIC_URL" <<'PY'
import re, sys
path, url = sys.argv[1], sys.argv[2]
text = open(path, encoding="utf-8").read()

def put(body, key, value):
    if re.search(rf"(?m)^{key}=.*$", body):
        return re.sub(rf"(?m)^{key}=.*$", f"{key}={value}", body)
    return body.rstrip("\n") + f"\n{key}={value}\n"

text = put(text, "NEXTAUTH_URL", url)
text = put(text, "NEXT_PUBLIC_SITE_URL", url)
text = re.sub(r"(?m)^NEXT_PUBLIC_WS_URL=.*$", "# NEXT_PUBLIC_WS_URL unset for the demo: same origin, through the tunnel", text)
open(path, "w", encoding="utf-8").write(text)
PY

# --force-recreate, not restart: the frontend's NEXT_PUBLIC_* values come
# from the compose `environment:` block, which is baked into the container
# at creation and beats anything in .env.local. A plain restart would keep
# pointing the browser at localhost:8000.
NEXT_PUBLIC_API_URL="$PUBLIC_URL" \
NEXT_PUBLIC_WS_URL="${PUBLIC_URL/https:/wss:}" \
  docker compose up -d --force-recreate frontend >/dev/null
printf "waiting for the frontend"
for _ in $(seq 1 45); do
  if curl -fsS -o /dev/null "http://localhost:3000/demo" 2>/dev/null; then break; fi
  printf "."; sleep 1
done
printf "\n"

cat <<BANNER

┌──────────────────────────────────────────────────────────────┐
  AUDIENCE LINK     $PUBLIC_URL/demo
  QR CODE SLIDE     $PUBLIC_URL/demo/qr
└──────────────────────────────────────────────────────────────┘

  Open the QR slide on the projector. Phones scan it and land in an
  unlocked Institutional session with a seeded book.

  Leave this terminal open. Ctrl-C ends the tunnel and restores
  $ENV_FILE.

BANNER

wait "$TUNNEL_PID"
